import assert from 'node:assert/strict';
import { createHostedPersistence } from '../../../src/serve/hosted/persistence.js';
import { createSandboxRoot, installHostedHistory } from 'pyric/sandbox/internal';
import { getFirestore, doc, setDoc, getDoc, updateDoc, increment, writeBatch, runTransaction, serverTimestamp } from 'pyric/firestore';
const directory = process.argv[2];
let persistence = await createHostedPersistence(directory);
let sandbox = createSandboxRoot();
await sandbox.enablePersistence({ key: 'hosted', injectedBackend: persistence.backend });
let engine = installHostedHistory(sandbox, persistence.history.engine, persistence.history.observe);
let db = getFirestore(sandbox);
for (const index of Array(1100).keys()) {
  await setDoc(doc(db, 'counter/one'), { value: index, padding: 'x'.repeat(4096) });
  await sandbox.flush();
}
assert.equal(persistence.history.engine.status().undoCount, 1100);
assert.ok(persistence.history.engine.status().cacheBytes <= 4 * 1024 * 1024);
sandbox.dispose();
persistence.close();
persistence = await createHostedPersistence(directory);
sandbox = createSandboxRoot();
await sandbox.enablePersistence({ key: 'hosted', injectedBackend: persistence.backend });
engine = installHostedHistory(sandbox, persistence.history.engine, persistence.history.observe);
db = getFirestore(sandbox);
for (const _index of Array(1050).keys())
  engine.undo();
await sandbox.flush();
assert.equal((await getDoc(doc(db, 'counter/one'))).data()?.value, 49);
assert.ok(persistence.history.engine.status().cachedRecords <= 1000);
assert.ok(persistence.history.engine.status().cacheBytes <= 4 * 1024 * 1024);
engine.redo();
await sandbox.flush();
assert.equal((await getDoc(doc(db, 'counter/one'))).data()?.value, 50);
await updateDoc(doc(db, 'counter/one'), { value: increment(10) });
await sandbox.flush();
assert.equal(engine.redo(), null, 'new writes invalidate redo without deleting the audit');
const batch = writeBatch(db);
batch.set(doc(db, 'batch/a'), { value: 1 });
batch.set(doc(db, 'batch/b'), { value: 2 });
await batch.commit();
await sandbox.flush();
engine.undo();
await sandbox.flush();
assert.equal((await getDoc(doc(db, 'batch/a'))).exists(), false);
assert.equal((await getDoc(doc(db, 'batch/b'))).exists(), false);
engine.redo();
await sandbox.flush();
await runTransaction(db, async (tx) => {
  await tx.get(doc(db, 'batch/a'));
  tx.update(doc(db, 'batch/a'), { value: increment(2), at: serverTimestamp() });
  tx.delete(doc(db, 'batch/b'));
});
await sandbox.flush();
const committed = (await getDoc(doc(db, 'batch/a'))).data();
engine.undo();
await sandbox.flush();
assert.equal((await getDoc(doc(db, 'batch/b'))).exists(), true);
engine.redo();
await sandbox.flush();
assert.deepEqual((await getDoc(doc(db, 'batch/a'))).data(), committed);
engine.undo();
await sandbox.flush();
assert.equal((await getDoc(doc(db, 'batch/a'))).data()?.value, 1);
assert.equal((await getDoc(doc(db, 'batch/b'))).exists(), true);
sandbox.reset();
await sandbox.flush();
assert.equal(persistence.history.engine.status().undoCount, 0);
assert.ok(persistence.history.status().durableSequence > 1100);
sandbox.dispose();
persistence.close();
console.log('Bounded undo passed');
