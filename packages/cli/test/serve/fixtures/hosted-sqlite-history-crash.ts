import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { writeFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { openHostedDatabase } from '../../../src/serve/hosted/persistence/database.js';
import { exportHistory, verifyHistoryArchive } from '../../../src/serve/hosted/persistence/history-export.js';
const directory = process.argv[2];
const databaseModule = new URL('../../../src/serve/hosted/persistence/database.js', import.meta.url).href;
const exportModule = new URL('../../../src/serve/hosted/persistence/history-export.js', import.meta.url).href;
const script = join(directory, 'crash.mjs');
writeFileSync(script, `
import fs from 'node:fs';
import { syncBuiltinESMExports } from 'node:module';
const mode = process.argv[3];
const rename = fs.renameSync;
const fsync = fs.fsyncSync;
const open = fs.openSync;
const handles = new Map();
fs.openSync = (...args) => { const fd = open(...args); handles.set(fd, String(args[0])); return fd; };
fs.fsyncSync = fd => { fsync(fd); if (mode === 'fsync' && handles.get(fd)?.includes('.segment-')) process.kill(process.pid, 'SIGKILL'); };
fs.renameSync = (from, to) => { rename(from, to); if (mode === 'rename' && String(to).endsWith('.jsonl')) process.kill(process.pid, 'SIGKILL'); };
syncBuiltinESMExports();
const { openHostedDatabase } = await import(${JSON.stringify(databaseModule)});
const { exportHistory } = await import(${JSON.stringify(exportModule)});
const db = await openHostedDatabase(process.argv[2]);
if (mode === 'observation') {
 db.history.startSession();
 db.history.observe({ kind:'operation', id:'uncommitted-tail', at:1, service:'ai' });
 process.kill(process.pid, 'SIGKILL');
} else await exportHistory(db.history, process.argv[4]);
`);
const source = join(directory, 'source');
let database = await openHostedDatabase(source);
database.history.observe({ kind: 'operation', id: 'committed', at: 1, service: 'messaging' });
database.history.flush();
database.close();
const interrupted = spawnSync(process.execPath, [script, source, 'observation'], { timeout: 5000 });
assert.equal(interrupted.signal, 'SIGKILL');
database = await openHostedDatabase(source);
assert.equal(database.history.status().previousShutdownClean, false);
database.history.startSession();
assert.equal(JSON.stringify(database.history.list()).includes('uncommitted-tail'), false);
assert.equal(JSON.stringify(database.history.list()).includes('unclean-restart'), true);
database.close();
for (const mode of ['fsync', 'rename']) {
  const output = join(directory, mode);
  const child = spawnSync(process.execPath, [script, source, mode, output], { timeout: 5000 });
  assert.equal(child.signal, 'SIGKILL');
  database = await openHostedDatabase(source);
  const result = await exportHistory(database.history, output);
  assert.equal(result.sequence, database.history.status().durableSequence);
  assert.equal((await verifyHistoryArchive(output)).records, result.sequence);
  assert.equal(readdirSync(output).filter(name => name.endsWith('.jsonl')).length, 1);
  database.close();
}
console.log('History crash recovery passed');
