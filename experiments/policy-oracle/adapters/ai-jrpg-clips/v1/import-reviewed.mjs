import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {readFileSync} from 'node:fs';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {immutable,jsonBytes,privateArchive} from '../../../arcade/live/controller/archive.mjs';
import {sha} from '../../../arcade/corpus.mjs';
import {bucketFor,probePath} from './fixture.mjs';

const [archiveArg,runId] = process.argv.slice(2);
bucketFor(runId);
const root = fileURLToPath(new URL('../../../',import.meta.url));
const probe = join(root,probePath), archive = privateArchive(archiveArg);
const completed = JSON.parse(readFileSync(join(archive,runId,'completed.json')));
assert.equal(completed.runId,runId);
assert.match(completed.digest,/^[a-f0-9]{64}$/);
const original = join(archive,completed.digest+'.json'), raw = readFileSync(original);
assert.equal(sha(raw),completed.digest);
assert.equal(JSON.parse(raw).runId,runId);
const verifier = fileURLToPath(new URL('./verify.mjs',import.meta.url));
const results = JSON.parse(execFileSync(process.execPath,[verifier,probe,original],{encoding:'utf8'}));
const recipe = readFileSync(join(probe,'recipe.json'));
assert.deepEqual(Object.keys(results).sort(),JSON.parse(recipe).cases.sort());
const inputDigest = sha(Buffer.concat([readFileSync(join(probe,'../../../claim.json')),Buffer.from([0]),recipe]));
const path = 'evidence/'+runId+'.json';
const evidence = {path,sha256:completed.digest,pointers:Object.fromEntries(Object.keys(results).map(id=>[id,'/rows/'+id+'/decision']))};
immutable(join(probe,path),raw,{identicalOk:true});
immutable(join(probe,'observations',runId+'.json'),jsonBytes({authority:'storage-production',inputDigest,results,evidence}),{identicalOk:true});
console.log('Imported',Object.keys(results).length,'live Storage SDK verdicts from',runId);
